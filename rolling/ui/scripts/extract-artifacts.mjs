import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..')
const wanted = {
  RollingBorrower: 'out/RollingBorrower.sol/RollingBorrower.json',
  MidnightRoller: 'out/MidnightRoller.sol/MidnightRoller.json',
  FlashRollLender: 'out/FlashRollLender.sol/FlashRollLender.json',
  TwoPartyGate: 'out/TwoPartyGate.sol/TwoPartyGate.json',
  MockCollateral: 'out/MockCollateral.sol/MockCollateral.json',
  FixedOracle: 'out/MockCollateral.sol/FixedOracle.json',
  DemoHelper: 'out/DemoHelper.sol/DemoHelper.json',
  IMidnight: 'out/IMidnight.sol/IMidnight.json',
  ISetterRatifier: 'out/ISetterRatifier.sol/ISetterRatifier.json',
}

const artifacts = {}
for (const [name, relative] of Object.entries(wanted)) {
  const path = join(root, relative)
  if (!existsSync(path)) throw new Error(`Missing ${relative}. Run forge build first.`)
  const json = JSON.parse(readFileSync(path, 'utf8'))
  artifacts[name] = { abi: json.abi, bytecode: json.bytecode?.object ?? '0x' }
}

writeFileSync(
  join(root, 'ui/src/artifacts.ts'),
  `// Generated by scripts/extract-artifacts.mjs.\nexport const artifacts = ${JSON.stringify(artifacts, null, 2)} as const\n`,
)
